/**
 * Writes MecHand's TikZ and chemfig exports of selected templates as .tex
 * fragments (used by the LaTeX tutorial). Skipped unless MECHAND_FIGURES_OUT
 * is set:  MECHAND_FIGURES_OUT=../tutorial/figures npm run export:figures
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, it } from 'vitest';
import { ketToScene } from '../scene/ketToScene';
import { TEMPLATES } from '../templates/catalog';
import { toChemfig } from './chemfig';
import { toTikz } from './tikz';

const OUT = process.env.MECHAND_FIGURES_OUT;
const IDS = (process.env.MECHAND_FIGURES ?? 'sn2,diels_alder,radical_homolysis,lewis_adduct').split(',');

describe.skipIf(!OUT)('export figures', () => {
  it('writes TikZ and chemfig fragments', () => {
    mkdirSync(OUT!, { recursive: true });
    for (const id of IDS) {
      const t = TEMPLATES.find((x) => x.id === id);
      if (!t) throw new Error(`Unknown template ${id}`);
      const scene = ketToScene(t.ket);
      const note = `% Generated by MecHand (npm run export:figures) from template "${id}". Do not edit.\n`;
      writeFileSync(join(OUT!, `${id}-tikz.tex`), note + toTikz(scene) + '\n');
      writeFileSync(join(OUT!, `${id}-chemfig.tex`), note + toChemfig(scene) + '\n');
    }
  });
});
