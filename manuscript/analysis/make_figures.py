"""Tables and figures for the manuscript from the analysis results.

  python make_figures.py      (needs matplotlib)

Writes results/benchmark.tex (per-template recognition benchmark) and
../figures/recognition-e2.pdf (synthetic handwriting of the E2 template, coloured
by how MecHand read each stroke).
"""
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = Path(__file__).parent
RES = HERE / "results"
FIG = HERE.parent / "figures"
FIG.mkdir(exist_ok=True)

# ── Benchmark table ──────────────────────────────────────────────────────────
bench = json.loads((RES / "benchmark.json").read_text())
index = {t["id"]: t for t in json.loads((HERE.parent.parent / "ketcher-mechhand/src/templates/index.json").read_text())}
names = {"organic": "Org.", "inorganic": "Inorg.", "biochemistry": "Biochem."}
lines = ["% Generated by manuscript/analysis/make_figures.py — do not edit by hand.",
         "\\begin{tabular}{llrrrr}", "\\toprule",
         "Template & Class & Atoms & Bonds & Arrows & Exact \\\\", "\\midrule"]
for r in bench["rows"]:
    t = index[r["id"]]
    title = t["title"].split(":")[0].replace("₂", "$_2$").replace("₄", "$_4$").replace("₃", "$_3$").replace("–", "--")
    lines.append(f"{title} & {names[t['category']]} & {100*r['atoms']:.0f} & {100*r['bonds']:.0f} & {100*r['arrows']:.0f} & {100*r['exact']:.0f} \\\\")
s = bench["summary"]
lines += ["\\midrule", f"Mean & & {100*s['atoms']:.0f} & {100*s['bonds']:.0f} & {100*s['arrows']:.0f} & {100*s['exact']:.0f} \\\\",
          "\\bottomrule", "\\end{tabular}"]
(RES / "benchmark.tex").write_text("\n".join(lines) + "\n")

# ── Figure: E2 drawn by hand, strokes coloured by role ──────────────────────────
d = json.loads((RES / "figure_e2.json").read_text())
colour = {"bond": "#2563eb", "arrow": "#dc2626", "arrowhead": "#dc2626", "text": "#059669", "dot": "#059669", "ignored": "#9ca3af"}
fig, ax = plt.subplots(figsize=(7.0, 2.4))
for pts, role in zip(d["strokes"], d["roles"]):
    ax.plot([p["x"] for p in pts], [p["y"] for p in pts], color=colour[role], lw=1.3, solid_capstyle="round")
ax.invert_yaxis(); ax.set_aspect("equal"); ax.axis("off")
for role, label in [("bond", "bond"), ("text", "atom label / charge"), ("arrow", "arrow")]:
    ax.plot([], [], color=colour[role], lw=2, label=label)
ax.legend(loc="lower right", frameon=False, fontsize=7, ncol=3)
fig.tight_layout(pad=0.1)
fig.savefig(FIG / "recognition-e2.pdf")
print("written", RES / "benchmark.tex", FIG / "recognition-e2.pdf")
